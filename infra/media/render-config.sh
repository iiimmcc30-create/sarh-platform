#!/bin/sh
# Renders livekit.yaml, egress.yaml and nginx.conf from environment variables
# (docker compose passes .env.media). Output goes to /out (the media_config volume),
# so nothing secret is ever written into the repository.
set -eu

OUT="${OUT_DIR:-/out}"
: "${LIVEKIT_API_KEY:?LIVEKIT_API_KEY is required}"
: "${LIVEKIT_API_SECRET:?LIVEKIT_API_SECRET is required}"

RTC_DOMAIN="${RTC_DOMAIN:-rtc.getsarh.com}"
TURN_DOMAIN="${TURN_DOMAIN:-turn.getsarh.com}"
NODE_IP="${NODE_IP:-}"
WEBHOOK_URL="${WEBHOOK_URL:-https://getsarh.com/api/livekit/webhook}"
REDIS_ADDRESS="${REDIS_ADDRESS:-}"
REDIS_USERNAME="${REDIS_USERNAME:-}"
REDIS_PASSWORD="${REDIS_PASSWORD:-}"
REDIS_TLS="${REDIS_TLS:-false}"
REDIS_TLS_SERVER_NAME="${REDIS_TLS_SERVER_NAME:-}"
REDIS_TLS_CA_FILE="${REDIS_TLS_CA_FILE:-}"
REDIS_TLS_CLIENT_CERT_FILE="${REDIS_TLS_CLIENT_CERT_FILE:-}"
REDIS_TLS_CLIENT_KEY_FILE="${REDIS_TLS_CLIENT_KEY_FILE:-}"
ROOM_MAX_PARTICIPANTS="${ROOM_MAX_PARTICIPANTS:-0}"
NODE_SYSLOAD_LIMIT="${NODE_SYSLOAD_LIMIT:-0.8}"
NODE_BYTES_PER_SEC="${NODE_BYTES_PER_SEC:-0}"
EGRESS_WS_URL="${EGRESS_WS_URL:-ws://127.0.0.1:7880}"

mkdir -p "$OUT"
umask 077

yaml_quote() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }
redis_block() {
  echo "redis:"
  echo "  address: $REDIS_ADDRESS"
  if [ -n "$REDIS_USERNAME" ]; then printf '  username: "%s"\n' "$(yaml_quote "$REDIS_USERNAME")"; fi
  if [ -n "$REDIS_PASSWORD" ]; then printf '  password: "%s"\n' "$(yaml_quote "$REDIS_PASSWORD")"; fi
  if [ "$REDIS_TLS" = "true" ]; then
    echo "  tls:"
    echo "    enabled: true"
    if [ -n "$REDIS_TLS_SERVER_NAME" ]; then echo "    server_name: $REDIS_TLS_SERVER_NAME"; fi
    if [ -n "$REDIS_TLS_CA_FILE" ]; then echo "    ca_cert_file: $REDIS_TLS_CA_FILE"; fi
    if [ -n "$REDIS_TLS_CLIENT_CERT_FILE" ]; then echo "    client_cert_file: $REDIS_TLS_CLIENT_CERT_FILE"; fi
    if [ -n "$REDIS_TLS_CLIENT_KEY_FILE" ]; then echo "    client_key_file: $REDIS_TLS_CLIENT_KEY_FILE"; fi
  fi
}

{
  echo "# Generated by infra/media/render-config.sh - do not edit (edit .env.media)."
  echo "port: 7880"
  echo "bind_addresses:"
  echo '  - ""'
  echo "log_level: info"
  echo "rtc:"
  echo "  tcp_port: 7881"
  echo "  port_range_start: 50000"
  echo "  port_range_end: 60000"
  if [ -n "$NODE_IP" ]; then
    echo "  use_external_ip: false"
    echo "  node_ip: $NODE_IP"
  else
    echo "  use_external_ip: true"
  fi
  echo "turn:"
  echo "  enabled: true"
  echo "  domain: $TURN_DOMAIN"
  echo "  tls_port: 5349"
  echo "  udp_port: 3478"
  echo "  relay_range_start: 30000"
  echo "  relay_range_end: 40000"
  echo "  cert_file: /certs/turn.crt"
  echo "  key_file: /certs/turn.key"
  echo "webhook:"
  echo "  api_key: $LIVEKIT_API_KEY"
  echo "  urls:"
  echo "    - $WEBHOOK_URL"
  echo "room:"
  echo "  auto_create: true"
  echo "  empty_timeout: 300"
  echo "  departure_timeout: 20"
  if [ "$ROOM_MAX_PARTICIPANTS" != "0" ]; then
    echo "  max_participants: $ROOM_MAX_PARTICIPANTS"
  fi
  if [ "$NODE_BYTES_PER_SEC" != "0" ]; then
    echo "limit:"
    echo "  bytes_per_sec: $NODE_BYTES_PER_SEC"
  fi
  if [ -n "$REDIS_ADDRESS" ]; then
    redis_block
    echo "node_selector:"
    echo "  kind: sysload"
    echo "  sysload_limit: $NODE_SYSLOAD_LIMIT"
    echo "  sort_by: sysload"
  fi
} > "$OUT/livekit.yaml"

if [ -n "$REDIS_ADDRESS" ]; then
  {
    echo "log_level: info"
    echo "api_key: $LIVEKIT_API_KEY"
    echo "api_secret: $LIVEKIT_API_SECRET"
    echo "ws_url: $EGRESS_WS_URL"
    echo "health_port: 9091"
    redis_block
  } > "$OUT/egress.yaml"
else
  rm -f "$OUT/egress.yaml"
fi

# Port 443 is shared: SNI picks TURN/TLS (LiveKit hardcodes turns:<domain>:443)
# or the Caddy HTTPS listener on 8443 (wss signalling).
cat > "$OUT/nginx.conf" <<NGINX
worker_processes auto;
pid /tmp/nginx.pid;
error_log stderr warn;
worker_rlimit_nofile 16384;
events { worker_connections 8192; }
stream {
  map \$ssl_preread_server_name \$sarh_upstream {
    $TURN_DOMAIN 127.0.0.1:5349;
    default      127.0.0.1:8443;
  }
  server {
    listen 443;
    ssl_preread on;
    proxy_pass \$sarh_upstream;
    proxy_connect_timeout 5s;
    proxy_timeout 1h;
  }
}
NGINX

chmod 644 "$OUT/nginx.conf"
echo "Rendered: $(ls "$OUT" | tr '\n' ' ')"
