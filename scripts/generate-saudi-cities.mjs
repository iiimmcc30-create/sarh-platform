#!/usr/bin/env node
/**
 * One city list for backend and app.
 * Source of truth: backend-nest/assets/geo/saudi-cities.json (seeded into "SaudiCity").
 * Writes app/constants/saudiCities.generated.ts. Run after editing the JSON:
 *   node scripts/generate-saudi-cities.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(join(root, 'backend-nest/assets/geo/saudi-cities.json'), 'utf8'));

const regions = data.regions.map((r) => ({ id: r.id, nameAr: r.nameAr, nameEn: r.nameEn, capitalId: r.capitalId }));
const cities = data.cities.map((c) => ({
  id: c.id,
  regionId: c.regionId,
  nameAr: c.nameAr,
  nameEn: c.nameEn,
  aliases: c.aliases,
  lat: c.lat,
  lng: c.lng,
}));

const out = `// AUTO-GENERATED by scripts/generate-saudi-cities.mjs from
// backend-nest/assets/geo/saudi-cities.json (v${data.version}). Do not edit by hand.
// City-centre coordinates are public reference data (no user or listing locations).

export type SaudiCityRegionEntry = { id: string; nameAr: string; nameEn: string; capitalId: string };

export type SaudiCityEntry = {
  id: string;
  regionId: string;
  nameAr: string;
  nameEn: string;
  aliases: string[];
  lat: number;
  lng: number;
};

export const SAUDI_CITIES_VERSION = ${data.version};

export const SAUDI_CITY_REGIONS: SaudiCityRegionEntry[] = ${JSON.stringify(regions, null, 2)};

export const SAUDI_CITIES: SaudiCityEntry[] = ${JSON.stringify(cities, null, 2)};
`;
writeFileSync(join(root, 'app/constants/saudiCities.generated.ts'), out);
console.log(`Wrote ${cities.length} cities in ${regions.length} regions`);
