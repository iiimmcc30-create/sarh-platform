export function getPolicyBySlug(slug: string): SarhPolicyDoc | undefined {
  return SARH_POLICIES.find((p) => p.slug === slug);
}

export function policyBodyToMarkdown(doc: SarhPolicyDoc): string {
  return doc.sections.map((s) => `## ${s.title}\n\n${s.body}`).join('\n\n');
}

export function parsePolicyBody(bodyAr: string): SarhPolicySection[] {
  const parts = bodyAr.split(/\n## /);
  const sections: SarhPolicySection[] = [];
  for (const part of parts) {
    const trimmed = part.replace(/^##\s*/, '').trim();
    if (!trimmed) continue;
    const nl = trimmed.indexOf('\n');
    if (nl === -1) {
      sections.push({ title: trimmed, body: '' });
    } else {
      sections.push({
        title: trimmed.slice(0, nl).trim(),
        body: trimmed.slice(nl).trim(),
      });
    }
  }
  return sections.length ? sections : [{ title: '', body: bodyAr }];
}
